/**
 * Combined cap on (definition YAML text + every prompt file it references),
 * enforced before a Run row is ever written (spec: "batas ukuran
 * ditegakkan saat validasi"). Not a number spec.md states explicitly — see
 * the written report.
 */
export const MAX_TOTAL_DEFINITION_BYTES = 2 * 1024 * 1024;

export interface TriggerRunInput {
  /** Client-generated (spec: "Id Run dibangkitkan klien") — a double-triggered id is rejected by the `runs` primary key, not by an application-level guard. */
  id: Id<"run">;
  repositoryId: Id<"repository">;
  pipelinePath: string;
  refBranch: string;
}

export interface TriggeredRun {
  run: Run;
  stepRuns: StepRun[];
}

/**
 * Everything `materializeRun` needs beyond the already-validated definition.
 * Shared by the manual trigger (issue #4) and Automation (issue #18) — the
 * two paths differ only in who the principal is, which ref the definition
 * was read from, and how a unique violation is interpreted; the birth of the
 * Run and its initial Graph is one transaction shape.
 */
export interface MaterializeRunInput {
  /** Server-generated by Automation; client-generated by the manual trigger. */
  id: Id<"run">;
  project: typeof projects.$inferSelect;
  pipelineRepository: typeof repositories.$inferSelect;
  pipelinePath: string;
  refBranch: string;
  refSha: string;
  triggerKind: "manual" | "automation";
  triggeredByPrincipalId: Id<"user"> | Id<"serviceaccount">;
  credentialPrincipalId: Id<"user"> | Id<"serviceaccount">;
  definitionText: string;
  pipeline: Pipeline;
  /**
   * Pre-read prompt file contents — the Automation queue path. The queue
   * snapshots the definition *and* its prompt files at event time ("definisi
   * dari ref yang dipicu"), so a drain must not re-read them from a ref that
   * may have moved since. Omitted for the direct paths, which read live from
   * `refSha`.
   */
  definitionFiles?: Record<string, string>;
}

